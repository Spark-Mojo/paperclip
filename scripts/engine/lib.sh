server_port_from_config() {
  local config_path="$1"
  node -e '
    const fs = require("fs");
    const cfg = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    process.stdout.write(String((cfg.server && cfg.server.port) || 3100));
  ' "$config_path"
}

server_host_from_config() {
  local config_path="$1"
  node -e '
    const fs = require("fs");
    const cfg = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    process.stdout.write((cfg.server && cfg.server.host) || "127.0.0.1");
  ' "$config_path"
}

# Mirrors cli/src/utils/health-url.ts buildLocalHealthUrl().
health_url() {
  local config_path="$1"
  local host port
  host="$(server_host_from_config "$config_path")"
  port="$(server_port_from_config "$config_path")"
  case "$host" in
    ""|0.0.0.0|::) host="127.0.0.1" ;;
  esac
  echo "http://$host:$port/api/health"
}

