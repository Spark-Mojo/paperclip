#!/usr/bin/env bash
# scripts/engine/lib.sh — shared helpers for install.sh / rollback.sh / status.sh.
#
# Layout assumptions (SPA-6060, ENGINE-MIGRATE leaf 4), all overridable via env
# for local dry-run testing:
#
#   ENGINE_ROOT           default: /home/jamesilsley
#   PAPERCLIP_HOME         default: $ENGINE_ROOT/.paperclip-831
#                          — this is the CLI's own PAPERCLIP_HOME env var
#                          (packages/shared/src/home-paths.ts resolvePaperclipHomeDir():
#                          `process.env.PAPERCLIP_HOME`, falls back to ~/.paperclip).
#   PAPERCLIP_INSTANCE_ID  default: default
#                          — the CLI's own instance id env var (same file,
#                          resolvePaperclipInstanceId()). Real instance state
#                          (config.json, db/, logs/, secrets/) lives at
#                          $PAPERCLIP_HOME/instances/$PAPERCLIP_INSTANCE_ID/
#                          (resolvePaperclipInstanceRoot()) — NOT directly at
#                          $PAPERCLIP_HOME. The handoff assumed the instance
#                          dir *was* PAPERCLIP_HOME; that is not how the CLI
#                          resolves it, so this file documents the real path
#                          and everything below derives from it.
#   CURRENT_LINK           default: $ENGINE_ROOT/paperclip-current
#   UNIT_NAME              default: paperclip-831.service
#                          NOTE: the CLI's own `paperclipai service install`
#                          command (cli/src/services/service-manager.ts
#                          systemdServiceName()) would name this unit
#                          `paperclipai.service` (instance "default") or
#                          `paperclipai-<id>.service`. `paperclip-831.service`
#                          is our own ops-layer naming per the handoff, laid
#                          on top of — not generated by — the CLI's mechanism.
#                          status.sh lists all `paperclip*` units so a mismatch
#                          with whatever leaf 2 actually installed is visible,
#                          not silently assumed.
#   EXPECTED_DB             default: paperclip831 (safety guard, see below)
#   BACKUP_DIR              default: $ENGINE_ROOT/paperclip-backups
#   STATE_DIR               default: $ENGINE_ROOT/.paperclip-engine
#   HEALTH_TIMEOUT_SECS      default: 90
#   HEALTH_POLL_SECS         default: 2
#   PAPERCLIP_ENGINE_ADOPT_EXISTING_PREFIX
#                            opt-in absolute npm prefix already serving the
#                            instance (for bigbox, /usr). Seeds CURRENT_LINK
#                            to that prefix and redirects the existing unit
#                            with one managed ExecStart-only drop-in.
#
# The systemd unit's ExecStart is
#   "$CURRENT_LINK/bin/paperclipai" run --instance "$PAPERCLIP_INSTANCE_ID"
# — i.e. it goes through the npm `-g --prefix` bin shim inside the *symlink*,
# not a hardcoded dist/index.js path in a specific version prefix. That is
# what makes "flip the symlink, restart the unit" a real cutover. See
# scripts/engine/systemd/paperclip-831.service, cited from
# cli/src/services/service-manager.ts renderSystemdUnit() (Type=notify,
# NotifyAccess=all, the three Environment= lines, Restart=always,
# RestartSec=5, TimeoutStopSec=300 are all copied from there — the server
# really does call sd_notify, see server/src/services/systemd-notify.ts and
# server/src/index.ts import of it).
#
# Health endpoint: GET /api/health (server/src/app.ts: `app.use("/api", api)`
# + `api.use("/health", healthRoutes(...))`; cli/src/utils/health-url.ts
# buildLocalHealthUrl() builds exactly this path). Body has a `status` field
# (== "ok" when healthy) and `version`/`serverVersion`.
#
# Migration table: "drizzle"."__drizzle_migrations" (packages/db/src/client.ts
# DRIZZLE_MIGRATIONS_TABLE).
#
# PAPERCLIP_ENGINE_DRY_RUN=1 — every external mutating command (npm, pnpm,
# git/curl fetch, systemctl, pg_dump, pg_restore, corepack) is logged and NOT
# executed; the install functions instead synthesize a minimal but
# structurally valid fake prefix (package.json + bin/paperclipai shim) so the
# surrounding orchestration (symlink flip, health wait, rollback-on-failure)
# can be exercised end to end without a real build or network access. See
# scripts/engine/tests/.

set -euo pipefail

