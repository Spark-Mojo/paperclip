# Refuse to run against a live host unless it looks like the intended target,
# or we are explicitly in a sandboxed dry-run test.
guard_host() {
  if [ "$DRY_RUN" = "1" ]; then
    return 0
  fi
  local os
  os="$(uname -s)"
  if [ "$os" != "Linux" ]; then
    die "This script targets Linux (bigbox). Refusing to run on '$os' outside PAPERCLIP_ENGINE_DRY_RUN=1. Never point it at the laptop's live paperclip."
  fi
}

# Refuse to touch a database that isn't the expected local instance DB. Reads
# database.connectionString / database.mode out of the *currently active*
# instance config (if any) via node — never sed/grep on a URI.
assert_expected_database() {
  local config_path="$1"
  if [ ! -f "$config_path" ]; then
    log "No existing instance config at $config_path yet (first install) — skipping database identity guard."
    return 0
  fi
  local info
  info="$(node -e '
    const fs = require("fs");
    const cfg = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    const db = cfg.database || {};
    if (db.mode !== "postgres" || !db.connectionString) {
      console.log("SKIP");
      process.exit(0);
    }
    const u = new URL(db.connectionString);
    console.log([u.hostname, (u.pathname || "").replace(/^\//, "")].join(" "));
  ' "$config_path")"
  if [ "$info" = "SKIP" ]; then
    log "Instance is not in postgres mode (or has no connectionString) — skipping database identity guard."
    return 0
  fi
  local host db_name
  host="$(echo "$info" | awk '{print $1}')"
  db_name="$(echo "$info" | awk '{print $2}')"
  case "$host" in
    127.0.0.1|localhost) ;;
    *) die "Refusing to operate: instance database host '$host' is not 127.0.0.1/localhost. This script only manages the local bigbox instance." ;;
  esac
  if [ "$db_name" != "$EXPECTED_DB" ]; then
    die "Refusing to operate: instance database name '$db_name' != expected '$EXPECTED_DB'. Set EXPECTED_DB if this is intentional."
  fi
}

connection_string_from_config() {
