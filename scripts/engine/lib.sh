prefix_version() {
  local prefix="$1"
  local pkg="$prefix/lib/node_modules/paperclipai/package.json"
  if [ ! -f "$pkg" ]; then
    die "No paperclipai package.json found at $pkg — prefix $prefix does not look installed."
  fi
  node -e 'console.log(JSON.parse(require("fs").readFileSync(process.argv[1], "utf8")).version)' "$pkg"
}

# Best-effort: locate the packed @paperclipai/server inside a prefix, to
# prove a fork install did not silently fall back to a registry server
# package. Not fatal if not found (layout can vary with npm's hoisting).
prefix_server_package_path() {
  local prefix="$1"
  find "$prefix/lib/node_modules" -maxdepth 4 -path '*/@paperclipai/server/package.json' 2>/dev/null | head -1
}

current_target() {
  if [ -L "$CURRENT_LINK" ]; then
    readlink "$CURRENT_LINK"
  else
    echo ""
  fi
}

record_previous_target() {
  local target="$1"
  mkdir -p "$STATE_DIR"
  if [ -n "$target" ]; then
    printf '%s\n' "$target" > "$PREVIOUS_STATE_FILE"
    log "Recorded previous prefix for rollback: $target"
  fi
}

read_previous_target() {
  if [ -f "$PREVIOUS_STATE_FILE" ]; then
    cat "$PREVIOUS_STATE_FILE"
  else
    echo ""
  fi
}

flip_symlink() {
  local target="$1"
  # Always a real filesystem operation, even under PAPERCLIP_ENGINE_DRY_RUN=1
  # — it is local, cheap, and it IS the state this script (and its tests)
  # exist to exercise; unlike npm/git/systemctl/pg_dump it is never stubbed.
  # ln -sfn atomically replaces an existing symlink (rename() under the
  # hood) on both GNU and BSD/macOS ln — unlike `mv`, which has the
  # well-known "moves INTO an existing symlink-to-directory" gotcha.
  log "+ ln -sfn $target $CURRENT_LINK"
  ln -sfn "$target" "$CURRENT_LINK"
}

# ---------------------------------------------------------------------------
# systemd
# ---------------------------------------------------------------------------

unit_stop() {
  run systemctl --user stop "$UNIT_NAME" || true
}

# Returns non-zero (does not `die`) if the unit fails to reach "started" —
# with Type=notify this call blocks until sd_notify(READY=1) or a timeout,
# so a broken new version legitimately makes this fail. Callers MUST check
# the return value themselves (never call this bare under `set -e` and
# expect to reach a rollback branch afterwards — a non-zero exit here would
# otherwise abort the whole script before rollback logic runs).
#
# PAPERCLIP_ENGINE_TEST_FAIL_START=1 forces a synthetic failure, for tests
# that need to exercise the rollback path without a real unit.
unit_start() {
  if [ "${PAPERCLIP_ENGINE_TEST_FAIL_START:-0}" = "1" ]; then
    log "+TESTHOOK simulating systemctl start failure (PAPERCLIP_ENGINE_TEST_FAIL_START=1)"
    return 1
  fi
  run systemctl --user start "$UNIT_NAME"
}

unit_restart() {
  run systemctl --user restart "$UNIT_NAME"
}

# Refuses to silently overwrite a unit file that already exists with
# different content — another operator/script (e.g. leaf 2's own install)
# may have put a different ExecStart there. Set
# PAPERCLIP_ENGINE_REPLACE_UNIT=1 to allow an intentional overwrite. A
# missing unit file is always installed (first run is not a conflict).
unit_ensure_installed() {
  local unit_path="$HOME/.config/systemd/user/$UNIT_NAME"
  local template="$1"
  if [ "$DRY_RUN" = "1" ]; then
    log "+DRYRUN would ensure unit file at $unit_path from $template"
    return 0
  fi
  mkdir -p "$(dirname "$unit_path")"
  if [ ! -f "$unit_path" ]; then
    log "Installing unit file $unit_path"
    cp "$template" "$unit_path"
    run systemctl --user daemon-reload
    return 0
  fi
  if ! cmp -s "$template" "$unit_path"; then
    if [ "${PAPERCLIP_ENGINE_REPLACE_UNIT:-0}" != "1" ]; then
      log "Existing unit file $unit_path differs from $template:"
      diff -u "$unit_path" "$template" >&2 || true
      die "Refusing to overwrite an existing, different unit file. Review the diff above; set PAPERCLIP_ENGINE_REPLACE_UNIT=1 to replace it deliberately."
    fi
    log "Replacing unit file $unit_path (PAPERCLIP_ENGINE_REPLACE_UNIT=1)"
    cp "$template" "$unit_path"
    run systemctl --user daemon-reload
  fi
}

