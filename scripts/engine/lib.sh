# Polls GET <url>; returns 0 and prints the JSON body on success (HTTP 2xx and
# body.status == "ok"), returns 1 after HEALTH_TIMEOUT_SECS otherwise.
wait_for_health() {
  local url="$1"
  local deadline=$(( $(date +%s) + HEALTH_TIMEOUT_SECS ))
  local body
  while [ "$(date +%s)" -lt "$deadline" ]; do
    if body="$(curl -fsS -m 5 "$url" 2>/dev/null)"; then
      if node -e '
          let input = "";
          process.stdin.on("data", (d) => (input += d));
          process.stdin.on("end", () => {
            try {
              const parsed = JSON.parse(input);
              process.exit(parsed.status === "ok" ? 0 : 1);
            } catch {
              process.exit(1);
            }
          });
        ' <<<"$body"; then
        echo "$body"
        return 0
      fi
    fi
    sleep "$HEALTH_POLL_SECS"
  done
  return 1
}

